import { describe, expect, it } from 'vitest';
import protocol from './protocol.generated.json';
import {
    agentMessageSchema,
    commandActionSchema,
    sandboxStageSchema,
    sessionStatusSchema,
    taskLogEntryTypeSchema,
    taskStatusSchema,
    toolStatusSchema
} from './schemas';

/**
 * Guards against the frontend's Zod enums drifting from the backend's.
 *
 * Every one of these vocabularies is written down twice, once in Python and
 * once here. If the backend gains a value that this side does not know, the
 * frontend rejects every message carrying it — surfacing to the user as an
 * unexplained validation error rather than as an obviously missing case. These
 * assertions turn that into a failed test at the moment of the change.
 *
 * The artefact is generated by `backend/scripts/export_protocol.py`.
 */
describe('protocol vocabulary', () => {
    it('knows every message type the backend can send', () => {
        const known = agentMessageSchema.options
            .map((option) => option.shape.type.value as string)
            .sort();

        expect(known).toEqual([...protocol.message_type].sort());
    });

    it('knows every session status the backend can announce', () => {
        expect([...sessionStatusSchema.options].sort()).toEqual(
            [...protocol.session_status].sort()
        );
    });

    it('knows every sandbox failure stage', () => {
        expect([...sandboxStageSchema.options].sort()).toEqual([...protocol.sandbox_stage].sort());
    });

    it('knows every tool status', () => {
        expect([...toolStatusSchema.options].sort()).toEqual([...protocol.tool_status].sort());
    });

    it('knows every task status', () => {
        expect([...taskStatusSchema.options].sort()).toEqual([...protocol.task_status].sort());
    });

    it('knows every task log entry type', () => {
        expect([...taskLogEntryTypeSchema.options].sort()).toEqual(
            [...protocol.task_log_entry_type].sort()
        );
    });

    it('sends only commands the backend accepts', () => {
        // Outbound commands are never validated on arrival, so this comparison
        // is the only thing standing between a renamed action and a command the
        // backend silently rejects.
        expect([...commandActionSchema.options].sort()).toEqual(
            [...protocol.command_action].sort()
        );
    });
});
